/**
 * Sanitize a source CSS entrypoint into a host-safe Tailwind v4 @theme registration
 * sheet — keeps @theme / @theme inline blocks and strips build-environment
 * directives (@plugin, @config, @source, plugin @imports) that break host Turbopack.
 */

/**
 * @param {string} css
 * @returns {string}
 */
export function extractTailwindThemeBlocks(css) {
  const blocks = [];
  const re = /@theme(?:\s+inline)?\s*\{/g;
  let match;
  while ((match = re.exec(css)) !== null) {
    const start = match.index;
    const braceStart = css.indexOf("{", start);
    if (braceStart === -1) break;
    const end = findMatchingBrace(css, braceStart);
    if (end === -1) break;
    blocks.push(css.slice(start, end + 1).trim());
    re.lastIndex = end + 1;
  }
  return blocks.join("\n\n");
}

/**
 * @param {string} css
 * @param {number} openIndex index of `{`
 * @returns {number} index of matching `}` or -1
 */
function findMatchingBrace(css, openIndex) {
  let depth = 0;
  for (let i = openIndex; i < css.length; i += 1) {
    const ch = css[i];
    if (ch === "{") depth += 1;
    else if (ch === "}") {
      depth -= 1;
      if (depth === 0) return i;
    }
  }
  return -1;
}

/**
 * Strip host-unsafe at-rules from a CSS string (used when copying whole sheets).
 * Prefer extractTailwindThemeBlocks for registration-only output.
 *
 * @param {string} css
 * @returns {string}
 */
export function stripHostUnsafeCssDirectives(css) {
  let out = css;
  // Drop @plugin / @config / @source lines (single-line forms)
  out = out.replace(/^\s*@(?:plugin|config|source)\b[^\n]*$/gm, "");
  // Drop @import of known plugin packages
  out = out.replace(
    /^\s*@import\s+["'](?:tw-animate-css|tailwindcss-radix|tailwind-scrollbar)["'][^;]*;/gm,
    "",
  );
  return out.replace(/\n{3,}/g, "\n\n").trim();
}

/**
 * Collect @theme token names from CSS (e.g. --color-subtle, --shadow-elevation-low).
 *
 * @param {string} css
 * @returns {Set<string>}
 */
export function collectThemeTokenNames(css) {
  const names = new Set();
  const themeCss = extractTailwindThemeBlocks(css);
  if (!themeCss) {
    // Also scan whole file for @theme-less hosts that declare tokens inline
    const re = /--((?:color|text-color|border-color|shadow|fill)-[\w-]+)\s*:/g;
    let m;
    while ((m = re.exec(css)) !== null) names.add(m[1]);
    return names;
  }
  const re = /--((?:color|text-color|border-color|shadow|fill)-[\w-]+)\s*:/g;
  let m;
  while ((m = re.exec(themeCss)) !== null) names.add(m[1]);
  return names;
}

/**
 * Build a host-safe registration CSS file body from one or more source CSS strings.
 *
 * @param {string[]} cssParts
 * @param {{ header?: string }} [options]
 * @returns {string}
 */
export function buildHostSafeThemeCss(cssParts, options = {}) {
  const header =
    options.header ??
    [
      "/*",
      " * Auto-extracted Tailwind @theme registration (host-safe).",
      " * Values resolve from the source token VALUES sheet (:root / theme classes).",
      " * Generated by proto-plugin extract-tailwind-theme.mjs — do not hand-merge @plugin lines.",
      " */",
      "",
    ].join("\n");

  const blocks = [];
  const seen = new Set();
  for (const part of cssParts) {
    const extracted = extractTailwindThemeBlocks(part);
    if (!extracted) continue;
    for (const block of extracted.split(/\n\n+/)) {
      const key = block.replace(/\s+/g, " ").trim();
      if (!key || seen.has(key)) continue;
      seen.add(key);
      blocks.push(block.trim());
    }
  }

  if (!blocks.length) return "";
  return `${header}${blocks.join("\n\n")}\n`;
}
